import assert from 'node:assert/strict';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

const manifests = [];
for (const entry of await readdir('src/levels', { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const path = resolve('src/levels', entry.name, 'manifest.ts');
  if (!existsSync(path)) continue;
  const { default: manifest } = await import(pathToFileURL(path));
  assert.equal(manifest.id, entry.name, 'Manifest id must match its folder');
  manifests.push(manifest);
}
manifests.sort((a, b) => a.number - b.number);
assert.equal(manifests.length, 13);
assert.equal(new Set(manifests.map(m => m.id)).size, manifests.length);
const hints = JSON.parse(await readFile('src/levels/hints.json', 'utf8'));
for (const [index, manifest] of manifests.entries()) {
  assert.equal(manifest.number, index + 1);
  assert.ok(manifest.id.startsWith(String(index + 1).padStart(2, '0') + '-'));
  assert.ok(manifest.route.startsWith(`/lab/${manifest.id}`));
  assert.ok(existsSync(`src/app${manifest.route}/page.tsx`));
  assert.ok(manifest.files.length > 0);
  for (const path of manifest.files) {
    assert.ok(resolve(path).startsWith(resolve('src') + sep));
    assert.ok(existsSync(path), `Missing source reference in ${manifest.id}`);
  }
  assert.ok(['Low', 'Medium', 'High', 'Critical'].includes(manifest.severity));
  for (const field of ['title', 'concept', 'symptom']) assert.ok(typeof manifest[field] === 'string' && manifest[field].length > 0);
  assert.ok(manifest.lesson.length > 0 && manifest.lesson.every(p => typeof p === 'string' && p.length > 0));
  assert.ok(manifest.checks.length > 0);
  assert.equal(new Set(manifest.checks.map(c => c.name)).size, manifest.checks.length);
  assert.ok(manifest.checks.every(c => typeof c.run === 'function' && c.name.length > 0));
  assert.equal(hints[manifest.id]?.length, 3);
  assert.ok(hints[manifest.id].every(h => typeof h === 'string' && /^[A-Za-z0-9+/]+={0,2}$/.test(h) && h.length % 4 === 0));
}
assert.deepEqual(Object.keys(hints).sort(), manifests.map(m => m.id).sort());
const catalog = manifests.map(({ id, number, title, concept, severity, symptom }) => ({ id, number, title, concept, severity, symptom }));
const generated = {
  'src/levels/generated/catalog.json': JSON.stringify(catalog, null, 2) + '\n',
  'src/levels/generated/loaders.ts': '// Generated by scripts/validate-curriculum.mjs --write. Do not edit.\n' +
    "import type { LevelManifest } from '@/shell/types';\n\n" +
    'export const loaders: Record<string, (() => Promise<{ default: LevelManifest }>) | undefined> = {\n' +
    manifests.map(m => `  '${m.id}': () => import('../${m.id}/manifest'),`).join('\n') + '\n};\n',
};
if (process.argv.includes('--write')) await mkdir('src/levels/generated', { recursive: true });
for (const [path, expected] of Object.entries(generated)) {
  if (process.argv.includes('--write')) await writeFile(path, expected);
  else assert.equal(await readFile(path, 'utf8').catch(() => ''), expected, `${path} is stale. Run npm run curriculum:generate.`);
}
console.log(`${manifests.length} incidents, ${manifests.reduce((n, m) => n + m.checks.length, 0)} checks, ${Object.keys(hints).length * 3} encoded hint tiers validated. No checks executed or hints decoded.`);
